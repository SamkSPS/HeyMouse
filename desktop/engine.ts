import { spawn, execFile, type ChildProcess } from 'node:child_process';
import { createHash, X509Certificate } from 'node:crypto';
import { access, cp, mkdir, readdir, stat, writeFile } from 'node:fs/promises';
import { constants } from 'node:fs';
import { isIP } from 'node:net';
import path from 'node:path';
import { promisify } from 'node:util';
import type { Device, EngineSettings, EngineStatus, ScreenPlacement } from '../shared/types';

const execFileAsync = promisify(execFile);
const SUPPORTED_VERSION = /^1\.27\./;

export interface EngineStartOptions {
  settings: EngineSettings;
  localDeviceId: string;
  devices: Device[];
  layout: ScreenPlacement[];
  /** Private key and certificate in PEM format. Never expose this to the renderer. */
  certificatePem: string;
  clipboardSharing?: boolean;
}
export interface EngineDetection {
  available: boolean;
  path: string | null;
  version: string | null;
  message: string;
}
export interface EngineManagerOptions {
  dataDir: string;
  resourcesDir?: string;
  onStatus?: (status: EngineStatus) => void;
  onLog?: (line: string) => void;
}

export function engineScreenName(deviceId: string): string {
  if (!deviceId) throw new Error('Identidade do dispositivo ausente.');
  return `hm-${createHash('sha256').update(deviceId).digest('hex').slice(0, 24)}`;
}

export function normalizeEngineFingerprint(value: string): string {
  const normalized = value.replace(/:/g, '').toLowerCase();
  if (!/^[a-f0-9]{64}$/.test(normalized)) throw new Error('Certificado de pareamento inválido.');
  return normalized;
}

function ini(value: string): string {
  if (/[\r\n\0]/.test(value)) throw new Error('Valor de configuração inválido.');
  return `"${value.replace(/\\/g, '/').replace(/"/g, '\\"')}"`;
}

/** Pure config generation, also used in protocol tests. Deskflow 1.27 schema. */
export function createEngineConfig(options: EngineStartOptions, configDir: string) {
  const { settings, localDeviceId } = options;
  if (!Number.isInteger(settings.port) || settings.port < 1024 || settings.port > 65535) {
    throw new Error('A porta deve estar entre 1024 e 65535.');
  }
  const paired = options.devices.filter((device) => device.paired && device.id !== localDeviceId);
  const permitted = new Set([localDeviceId, ...paired.map((device) => device.id)]);
  const placements: ScreenPlacement[] = options.layout
    .filter((item) => permitted.has(item.deviceId))
    .map((item) => ({ ...item }));
  const seen = new Set<string>();
  const positions = new Set<string>();
  for (const item of placements) {
    if (!Number.isFinite(item.x) || !Number.isFinite(item.y)) throw new Error('Posição de tela inválida.');
    if (seen.has(item.deviceId)) throw new Error('Dispositivo duplicado na disposição de telas.');
    const position = `${item.x}:${item.y}`;
    if (positions.has(position)) throw new Error('Duas telas não podem ocupar a mesma posição.');
    seen.add(item.deviceId);
    positions.add(position);
  }
  if (!seen.has(localDeviceId)) {
    // The local screen is always present, even on the first launch.
    if (positions.has('0:0')) throw new Error('Reserve a posição central para este computador.');
    placements.unshift({ deviceId: localDeviceId, x: 0, y: 0 });
    seen.add(localDeviceId);
  }
  let nextX = Math.max(0, ...placements.map((item) => item.x)) + 1;
  for (const peer of paired) {
    if (!seen.has(peer.id)) placements.push({ deviceId: peer.id, x: nextX++, y: 0 });
  }
  const localName = engineScreenName(localDeviceId);
  const linkLines: string[] = ['# Generated by HeyMouse for Deskflow 1.27', 'section: links'];
  for (const screen of placements) {
    linkLines.push(`  ${engineScreenName(screen.deviceId)}:`);
    const directions = [
      { name: 'left', candidates: placements.filter((p) => p.y === screen.y && p.x < screen.x), distance: (p: ScreenPlacement) => screen.x - p.x },
      { name: 'right', candidates: placements.filter((p) => p.y === screen.y && p.x > screen.x), distance: (p: ScreenPlacement) => p.x - screen.x },
      { name: 'up', candidates: placements.filter((p) => p.x === screen.x && p.y < screen.y), distance: (p: ScreenPlacement) => screen.y - p.y },
      { name: 'down', candidates: placements.filter((p) => p.x === screen.x && p.y > screen.y), distance: (p: ScreenPlacement) => p.y - screen.y },
    ];
    for (const direction of directions) {
      const neighbor = direction.candidates.sort((a, b) => direction.distance(a) - direction.distance(b))[0];
      if (neighbor) linkLines.push(`    ${direction.name} = ${engineScreenName(neighbor.deviceId)}`);
    }
  }
  linkLines.push('end', 'section: options', `  keystroke(Control+Alt+Pause) = switchToScreen(${localName})`, 'end', '');
  const certificatePath = path.join(configDir, 'tls', 'heymouse.pem');
  const linksPath = path.join(configDir, 'layout.conf');
  let remoteHost = '';
  let inputPort = settings.port;
  if (settings.role === 'client') {
    const server = paired.find((device) => device.id === settings.serverDeviceId);
    if (!server) throw new Error('Selecione um computador pareado para fornecer mouse e teclado.');
    if (!server.engineFingerprint) throw new Error('O computador selecionado ainda não informou o certificado do motor.');
    if (!server.addresses.length) throw new Error('O endereço do computador pareado ainda não foi encontrado.');
    if (!Number.isInteger(server.inputPort) || server.inputPort < 1024 || server.inputPort > 65535) {
      throw new Error('O computador informou uma porta inválida.');
    }
    // Multiple authenticated discovery addresses support Ethernet/Wi-Fi changes.
    remoteHost = server.addresses.filter((address) => isIP(address.split('%')[0]) && /^[a-zA-Z0-9:.%_-]+$/.test(address))
      .map((address) => address.includes(':') ? `[${address}]` : address).join(',');
    if (!remoteHost) throw new Error('Nenhum endereço de rede válido foi encontrado.');
    inputPort = server.inputPort;
  }
  const trustedPeers = paired.filter((peer) => settings.role === 'server' || peer.id === settings.serverDeviceId);
  const fingerprints = [...new Set(trustedPeers.filter((peer) => peer.engineFingerprint)
    .map((peer) => normalizeEngineFingerprint(peer.engineFingerprint!)))];
  const trust = fingerprints.map((fingerprint) => `v2:sha256:${fingerprint}`).join('\n') + '\n';
  const sections = [
    '[core]', `coreMode=${settings.role === 'server' ? 2 : 1}`, `computerName=${localName}`,
    `port=${inputPort}`, 'processMode=1', 'useHooks=true', 'preventSleep=false',
    'enableEnterCommand=false', 'enableExitCommand=false', '',
    '[security]', 'tlsEnabled=true', 'checkPeerFingerprints=true', `certificate=${ini(certificatePath)}`, '',
    '[log]', 'level=INFO', 'toFile=false', '',
    '[client]', `remoteHost=${ini(remoteHost)}`, 'dynamicConnectionInterval=false', 'languageSync=false', '',
    '[server]', 'externalConfig=true', `externalConfigFile=${ini(linksPath)}`, 'protocol=barrier',
    `enableClipboard=${options.clipboardSharing === true}`, 'enableHeartbeat=true', 'heartbeat=1000',
    'enableSwitchDelay=false', 'enableSwitchDoubleTap=false', 'relativeMouseMoves=false', '',
  ];
  for (const screen of placements) {
    const name = engineScreenName(screen.deviceId);
    sections.push(`[computer_${name}]`, `name=${name}`, 'switchCornerSize=0', '');
  }
  return { settingsText: sections.join('\n'), linksText: linkLines.join('\n'), trust,
    settingsPath: path.join(configDir, 'Deskflow.conf'), linksPath, certificatePath };
}

async function executableAt(file: string): Promise<boolean> {
  try { await access(file, process.platform === 'win32' ? constants.F_OK : constants.X_OK); return (await stat(file)).isFile(); }
  catch { return false; }
}

async function findBundled(dir: string, depth = 2): Promise<string | null> {
  const basename = process.platform === 'win32' ? 'deskflow-core.exe' : 'deskflow-core';
  if (await executableAt(path.join(dir, basename))) return path.join(dir, basename);
  if (depth <= 0) return null;
  try {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      if (entry.isDirectory()) {
        const found = await findBundled(path.join(dir, entry.name), depth - 1);
        if (found) return found;
      }
    }
  } catch { /* optional bundled engine not downloaded */ }
  return null;
}

export async function detectEnginePath(explicitPath = '', resourcesDir?: string): Promise<string | null> {
  if (explicitPath) return await executableAt(explicitPath) ? explicitPath : null;
  if (resourcesDir) {
    if (process.platform === 'darwin') {
      const bundledMac = path.join(resourcesDir, 'Deskflow.app/Contents/MacOS/deskflow-core');
      if (await executableAt(bundledMac)) return bundledMac;
    }
    const bundled = await findBundled(resourcesDir);
    if (bundled) return bundled;
  }
  const candidates = process.platform === 'win32'
    ? [path.join(process.env.ProgramFiles ?? 'C:/Program Files', 'Deskflow', 'deskflow-core.exe')]
    : process.platform === 'darwin'
      ? ['/Applications/Deskflow.app/Contents/MacOS/deskflow-core', '/opt/homebrew/bin/deskflow-core', '/usr/local/bin/deskflow-core']
      : ['/usr/bin/deskflow-core', '/usr/local/bin/deskflow-core'];
  const binary = process.platform === 'win32' ? 'deskflow-core.exe' : 'deskflow-core';
  for (const directory of (process.env.PATH ?? '').split(path.delimiter).filter(Boolean)) candidates.push(path.join(directory, binary));
  for (const candidate of candidates) if (await executableAt(candidate)) return candidate;
  return null;
}

export class EngineManager {
  private child: ChildProcess | null = null;
  private desired: EngineStartOptions | null = null;
  private restartTimer: ReturnType<typeof setTimeout> | null = null;
  private startupTimer: ReturnType<typeof setTimeout> | null = null;
  private retries = 0;
  private generation = 0;
  private status: EngineStatus = { status: 'stopped', message: 'Compartilhamento pausado.', version: null, executablePath: null, logs: [] };

  constructor(private readonly options: EngineManagerOptions) {}

  getStatus(): EngineStatus { return { ...this.status, logs: [...this.status.logs] }; }

  private publish(patch: Partial<EngineStatus>) {
    this.status = { ...this.status, ...patch };
    this.options.onStatus?.(this.getStatus());
  }

  private log(line: string) {
    // INFO only: never enable event-level keyboard/mouse debug logging.
    const clean = line.replace(/\x1b\[[0-9;]*m/g, '').trim().slice(0, 1800);
    if (!clean) return;
    this.status.logs = [...this.status.logs.slice(-119), clean];
    this.options.onLog?.(clean);
    if (/an instance of deskflow core is already running/i.test(clean)) {
      this.desired = null;
      this.publish({ status: 'error', message: 'O Deskflow já está em execução. Pause o compartilhamento nele antes de iniciar o HeyMouse.' });
    } else if (/\b(?:ERROR|FATAL|CRITICAL)\b|failed to start|cannot listen|cannot read configuration/i.test(clean)) {
      this.publish({ message: clean });
    } else if (/connected to server|client .* has connected|accepted client connection/i.test(clean)) {
      this.retries = 0;
      this.publish({ status: 'running', message: 'Compartilhamento conectado com criptografia TLS.' });
    } else if (/disconnected|failed to connect|connection refused|connection timed out/i.test(clean)) {
      this.publish({ message: 'Aguardando o computador pareado. Reconexão automática ativa.' });
    }
  }

  async detect(executablePath = ''): Promise<EngineDetection> {
    const executable = await detectEnginePath(executablePath, this.options.resourcesDir);
    if (!executable) {
      const result = { available: false, path: null, version: null, message: 'Motor Deskflow 1.27 não encontrado. Selecione deskflow-core ou baixe o motor.' };
      this.publish({ executablePath: null, version: null, ...(this.child ? {} : { message: result.message }) });
      return result;
    }
    try {
      const { stdout, stderr } = await execFileAsync(executable, ['--version'], { timeout: 7000, windowsHide: true, maxBuffer: 64 * 1024 });
      const version = `${stdout}\n${stderr}`.match(/\bv?(\d+\.\d+\.\d+(?:\.\d+)?)\b/)?.[1] ?? null;
      const available = version !== null && SUPPORTED_VERSION.test(version);
      const message = available ? `Deskflow ${version} disponível.` : `Versão ${version ?? 'desconhecida'}: esta integração requer Deskflow 1.27.x.`;
      this.publish({ executablePath: executable, version });
      return { available, path: executable, version, message };
    } catch (error) {
      return { available: false, path: executable, version: null, message: `Não foi possível executar o motor: ${(error as Error).message}` };
    }
  }

  private async prepareRuntime(executable: string): Promise<{ executable: string; configDir: string }> {
    if (process.platform !== 'win32') return { executable, configDir: path.join(this.options.dataDir, 'engine-settings') };
    // Windows Deskflow otherwise uses ProgramData even when --settings is supplied.
    // A private portable copy isolates HeyMouse certificates, trust and configuration.
    const file = await stat(executable);
    const key = createHash('sha256').update(`${executable}:${file.size}:${file.mtimeMs}`).digest('hex').slice(0, 12);
    const runtimeDir = path.join(this.options.dataDir, 'engine-runtime', key);
    const runtimeExecutable = path.join(runtimeDir, 'deskflow-core.exe');
    const marker = path.join(runtimeDir, '.ready');
    try { await access(marker); }
    catch {
      await mkdir(runtimeDir, { recursive: true });
      const sourceDir = path.dirname(executable);
      if (path.resolve(runtimeDir).startsWith(path.resolve(sourceDir) + path.sep)) {
        throw new Error('O diretório do motor não pode conter os dados do HeyMouse.');
      }
      await cp(sourceDir, runtimeDir, {
        recursive: true,
        filter: (source) => !['settings', '.git', 'node_modules'].includes(path.relative(sourceDir, source).split(path.sep)[0]),
      });
      await writeFile(marker, 'HeyMouse private Deskflow runtime\n');
    }
    return { executable: runtimeExecutable, configDir: path.join(runtimeDir, 'settings') };
  }

  async start(options: EngineStartOptions): Promise<void> {
    await this.stop();
    this.desired = structuredClone(options);
    this.retries = 0;
    const generation = this.generation;
    try { await this.launch(options, generation); }
    catch (error) {
      this.desired = null;
      this.publish({ status: 'error', message: (error as Error).message });
      throw error;
    }
  }

  private async launch(options: EngineStartOptions, generation: number): Promise<void> {
    const detection = await this.detect(options.settings.executablePath);
    if (!detection.available || !detection.path) throw new Error(detection.message);
    if (generation !== this.generation) return;
    const runtime = await this.prepareRuntime(detection.path);
    if (generation !== this.generation) return;
    const config = createEngineConfig(options, runtime.configDir);
    // Parse before persisting; a certificate without a private key cannot serve TLS.
    new X509Certificate(options.certificatePem);
    if (!/-----BEGIN (?:RSA |EC )?PRIVATE KEY-----/.test(options.certificatePem)) throw new Error('Chave privada TLS ausente.');
    await mkdir(path.dirname(config.certificatePath), { recursive: true });
    await Promise.all([
      writeFile(config.settingsPath, config.settingsText, { mode: 0o600 }),
      writeFile(config.linksPath, config.linksText, { mode: 0o600 }),
      writeFile(config.certificatePath, options.certificatePem, { mode: 0o600 }),
      writeFile(path.join(runtime.configDir, 'tls', 'trusted-clients'), config.trust, { mode: 0o600 }),
      writeFile(path.join(runtime.configDir, 'tls', 'trusted-servers'), config.trust, { mode: 0o600 }),
    ]);
    if (generation !== this.generation) return;
    this.publish({ status: 'starting', message: 'Iniciando o motor nativo...' });
    const child = spawn(runtime.executable, [options.settings.role, '--settings', config.settingsPath], {
      cwd: path.dirname(runtime.executable), windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'],
    });
    this.child = child;
    for (const stream of [child.stdout, child.stderr]) {
      let pending = '';
      stream?.setEncoding('utf8');
      stream?.on('data', (data: string) => {
        if (generation !== this.generation) return;
        pending += data;
        const lines = pending.split(/\r?\n/);
        pending = lines.pop()!.slice(-4096);
        for (const line of lines) this.log(line);
      });
    }
    child.once('error', (error) => { if (generation === this.generation) this.publish({ status: 'error', message: error.message }); });
    child.once('exit', (code) => {
      if (generation !== this.generation) return;
      this.child = null;
      if (this.startupTimer) clearTimeout(this.startupTimer);
      if (!this.desired) return;
      this.retries++;
      if (this.retries > 5) {
        this.desired = null;
        this.publish({ status: 'error', message: 'O motor encerrou repetidamente. Confira permissões do sistema e o diagnóstico.' });
        return;
      }
      const delay = Math.min(1000 * 2 ** (this.retries - 1), 15000);
      this.publish({ status: 'starting', message: `Motor encerrado (${code ?? 'sinal'}). Nova tentativa em ${delay / 1000}s.` });
      this.restartTimer = setTimeout(() => {
        if (!this.desired || generation !== this.generation) return;
        void this.launch(this.desired, generation).catch((error: Error) => {
          this.desired = null;
          this.publish({ status: 'error', message: error.message });
        });
      }, delay);
      this.restartTimer.unref();
    });
    this.startupTimer = setTimeout(() => {
      if (this.child !== child || generation !== this.generation || this.status.status === 'running') return;
      this.publish({ status: 'running', message: options.settings.role === 'server'
        ? 'Motor ativo. Aguardando os computadores pareados.' : 'Motor ativo. Conectando ao computador pareado.' });
    }, 1200);
    this.startupTimer.unref();
  }

  async stop(): Promise<void> {
    this.generation++;
    this.desired = null;
    if (this.restartTimer) clearTimeout(this.restartTimer);
    if (this.startupTimer) clearTimeout(this.startupTimer);
    this.restartTimer = null;
    this.startupTimer = null;
    const child = this.child;
    this.child = null;
    if (child && child.exitCode === null) {
      await new Promise<void>((resolve) => {
        const timeout = setTimeout(() => { child.kill('SIGKILL'); resolve(); }, 2500);
        child.once('exit', () => { clearTimeout(timeout); resolve(); });
        child.kill();
      });
    }
    this.publish({ status: 'stopped', message: 'Compartilhamento pausado.' });
  }
}
